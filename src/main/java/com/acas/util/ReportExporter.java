package com.acas.util;

import com.acas.model.AcasFinding;
import com.acas.model.HuntConfig;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

public final class ReportExporter {
    private static final int BODY_LIMIT = 500;

    private ReportExporter() {
    }

    public static void exportMarkdown(List<AcasFinding> findings, HuntConfig config, File outputFile) throws IOException {
        StringBuilder sb = new StringBuilder();
        String exportDate = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));

        sb.append("# ACAS Hunt Report\n");
        sb.append("**Target:** ").append(valueOrDash(config != null ? config.getTargetHost() : null)).append("  \n");
        sb.append("**Date:** ").append(exportDate).append("  \n");
        sb.append("**Total Confirmed Findings:** ").append(findings != null ? findings.size() : 0).append("  \n");
        sb.append("**Hunt Duration:** ")
            .append(valueOrDash(config != null ? config.getStartTime() : null))
            .append(" -> ")
            .append(valueOrDash(config != null ? config.getEndTime() : null))
            .append("\n\n");

        sb.append("---\n\n");
        sb.append("## Summary Table\n\n");
        sb.append("| # | Severity | Endpoint | Method | Actor | Mutation | Score |\n");
        sb.append("|---|----------|----------|--------|-------|----------|-------|\n");

        if (findings != null) {
            for (int i = 0; i < findings.size(); i++) {
                AcasFinding f = findings.get(i);
                sb.append("| ").append(i + 1)
                    .append(" | ").append(md(valueOrDash(f.getSeverity())))
                    .append(" | ").append(md(valueOrDash(f.getEndpointPattern())))
                    .append(" | ").append(md(valueOrDash(f.getMethod())))
                    .append(" | ").append(md(valueOrDash(f.getReplayerActorName())))
                    .append(" | ").append(md(valueOrDash(f.getMutationType())))
                    .append(" | ").append(f.getConfidenceScore())
                    .append(" |\n");
            }
        }

        sb.append("\n---\n\n");

        if (findings != null) {
            for (int i = 0; i < findings.size(); i++) {
                AcasFinding f = findings.get(i);
                sb.append("## Finding #").append(i + 1).append(" - ")
                    .append(valueOrDash(f.getSeverity())).append(": ")
                    .append(valueOrDash(f.getEndpointPattern())).append("\n\n");

                sb.append("**Confidence Score:** ").append(f.getConfidenceScore()).append(" / 100  \n");
                sb.append("**Mutation:** ").append(valueOrDash(f.getMutationType()));
                if (f.getMutationDescription() != null && !f.getMutationDescription().isBlank()) {
                    sb.append(" - ").append(f.getMutationDescription());
                }
                sb.append("  \n");
                sb.append("**Actors:** ").append(valueOrDash(f.getOwnerActorName()))
                    .append(" -> ").append(valueOrDash(f.getReplayerActorName())).append("  \n");
                sb.append("**Status Code:** ").append(f.getMutatedStatus()).append("  \n");
                sb.append("**Owner Similarity:** ").append(percent(f.getSimilarityToOwner())).append("  \n");
                sb.append("**Anonymous Similarity:** ").append(percent(f.getSimilarityToAnon())).append("  \n");
                sb.append("**Confirmed By Differential Analysis:** ").append(f.isConfirmedByDiff() ? "Yes" : "No").append("\n\n");

                sb.append("### Request (Mutated)\n");
                sb.append("```http\n").append(truncate(sanitizeRequest(f.getMutatedRequest()), BODY_LIMIT)).append("\n```\n\n");

                sb.append("### Response (truncated to 500 chars)\n");
                sb.append("```json\n").append(truncate(extractBody(f.getMutatedResponse()), BODY_LIMIT)).append("\n```\n\n");

                sb.append("### Path to Issue\n");
                sb.append(pathToIssue(f)).append("\n\n");
                sb.append("---\n\n");
            }
        }

        sb.append("*Generated by ACAS - Access Control Assessment System*\n");

        try (FileWriter writer = new FileWriter(outputFile, StandardCharsets.UTF_8)) {
            writer.write(sb.toString());
        }
    }

    private static String pathToIssue(AcasFinding f) {
        StringBuilder sb = new StringBuilder();
        sb.append("Replay actor ").append(valueOrDash(f.getReplayerActorName()))
            .append(" accessed ").append(valueOrDash(f.getMethod()))
            .append(" ").append(valueOrDash(f.getUrl()));
        if (f.getFpReason() != null && !f.getFpReason().isBlank()) {
            sb.append(". FP analysis: ").append(f.getFpReason());
        }
        if (f.getAnalysisNote() != null && !f.getAnalysisNote().isBlank()) {
            sb.append(". Note: ").append(f.getAnalysisNote());
        }
        return sb.toString();
    }

    private static String sanitizeRequest(byte[] data) {
        String request = rawText(data);
        if (request.isBlank()) {
            return "<no request captured>";
        }

        String[] lines = request.split("\\r?\\n", -1);
        StringBuilder out = new StringBuilder();
        boolean inHeaders = true;
        for (String line : lines) {
            if (inHeaders) {
                if (line.isEmpty()) {
                    inHeaders = false;
                    out.append("\n");
                    continue;
                }
                String lower = line.toLowerCase();
                if (lower.startsWith("authorization:")) {
                    out.append("Authorization: Bearer [REDACTED]\n");
                } else if (lower.startsWith("cookie:")) {
                    out.append("Cookie: [REDACTED]\n");
                } else if (lower.startsWith("x-auth-token:")) {
                    out.append("X-Auth-Token: [REDACTED]\n");
                } else {
                    out.append(line).append("\n");
                }
            } else {
                out.append(line).append("\n");
            }
        }
        return out.toString().trim();
    }

    private static String extractBody(byte[] rawResponse) {
        String text = rawText(rawResponse);
        int idx = text.indexOf("\r\n\r\n");
        if (idx >= 0) return text.substring(idx + 4);
        idx = text.indexOf("\n\n");
        if (idx >= 0) return text.substring(idx + 2);
        return text;
    }

    private static String rawText(byte[] data) {
        if (data == null || data.length == 0) {
            return "";
        }
        return new String(data, StandardCharsets.ISO_8859_1);
    }

    private static String truncate(String text, int max) {
        if (text == null || text.isBlank()) {
            return "<no data captured>";
        }
        if (text.length() <= max) {
            return text;
        }
        return text.substring(0, max) + "\n... (truncated)";
    }

    private static String percent(double value) {
        double normalized = Math.max(0.0, Math.min(1.0, value));
        return String.format("%.0f%%", normalized * 100.0);
    }

    private static String md(String value) {
        return value.replace("|", "\\|");
    }

    private static String valueOrDash(String value) {
        return value == null || value.isBlank() ? "-" : value;
    }
}
