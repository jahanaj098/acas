package com.acas.util;

import com.acas.model.AcasFinding;
import com.acas.model.ActorProfile;
import com.acas.model.CapturedEndpoint;

import java.nio.charset.StandardCharsets;
import java.util.List;

public class ReportGenerator {

    /**
     * Generates a Markdown bug report for a captured endpoint finding.
     */
    public static String generateMarkdown(CapturedEndpoint ep, List<ActorProfile> allActors) {
        StringBuilder sb = new StringBuilder();

        sb.append("# [ACAS] Authorization Bypass: ").append(valueOrDash(ep.getClassificationLabel())).append("\n\n");

        sb.append("## Evidence Summary\n");
        sb.append("- **URL**: `").append(valueOrDash(ep.getOriginalUrl())).append("`\n");
        sb.append("- **Method**: `").append(valueOrDash(ep.getMethod())).append("`\n");
        sb.append("- **Target Path**: `").append(valueOrDash(ep.getNormalizedPath())).append("`\n");
        sb.append("- **Actor**: `").append(valueOrDash(ep.getActorId())).append("`\n");
        sb.append("- **Classification**: `").append(valueOrDash(ep.getClassificationLabel())).append("`\n");

        CapturedEndpoint.ProbeResult brokenProbe = findBrokenProbe(ep);
        if (brokenProbe != null) {
            sb.append("- **Triggered By**: `").append(valueOrDash(brokenProbe.actorName)).append("`\n");
            sb.append("- **Mutated Status**: `").append(brokenProbe.statusCode).append("`\n");
            sb.append("- **Leaked Fields**: `").append(valueOrDash(brokenProbe.leakedFields)).append("`\n");
        }

        sb.append("\n## How It Became An Issue\n");
        sb.append("ACAS replayed the captured request as alternate identities and compared the owner response with the replayed response. ");
        sb.append("If the alternate actor receives content that should be denied, or a response that matches the owner response too closely, the endpoint is flagged.\n\n");

        sb.append("## Requests Used\n");
        appendRequestBlock(sb, "Owner / Baseline Request", ep.getOriginalRequest() != null ? ep.getOriginalRequest().toByteArray().getBytes() : null);
        if (brokenProbe != null) {
            appendRequestBlock(sb, "Mutated / Replay Request", brokenProbe.request);
            appendResponseBlock(sb, "Mutated / Replay Response", brokenProbe.response);
        }

        sb.append("## Technical Details\n");
        sb.append("- **Priority Score**: `").append(ep.getPriorityScore()).append("`\n");
        sb.append("- **Confidence Score**: `").append(ep.getConfidenceScore()).append("`\n");
        sb.append("- **Hunt Status**: `").append(valueOrDash(String.valueOf(ep.getHuntStatus()))).append("`\n");
        sb.append("- **Last Hunt**: `").append(ep.getLastHuntTime() > 0 ? String.valueOf(ep.getLastHuntTime()) : "-").append("`\n\n");

        sb.append("## Impact\n");
        if (brokenProbe != null && !brokenProbe.leakedFields.isEmpty() && !"---".equals(brokenProbe.leakedFields)) {
            sb.append("Unauthorized access exposed the following fields: `").append(brokenProbe.leakedFields).append("`.\n\n");
        } else {
            sb.append("Unauthorized access was observed for this endpoint, allowing a lower-privileged or alternate actor to reach protected data or functionality.\n\n");
        }

        sb.append("--- \n");
        sb.append("*Generated by ACAS (Access Control Attack Simulator)*");

        return sb.toString();
    }

    /**
     * Generates a Markdown bug report for a matrix finding.
     */
    public static String generateMarkdown(AcasFinding finding) {
        StringBuilder sb = new StringBuilder();

        sb.append("# [ACAS] ").append(valueOrDash(finding.getLabel())).append("\n\n");

        sb.append("## Evidence Summary\n");
        sb.append("- **URL**: `").append(valueOrDash(finding.getUrl())).append("`\n");
        sb.append("- **Method**: `").append(valueOrDash(finding.getMethod())).append("`\n");
        sb.append("- **Endpoint Pattern**: `").append(valueOrDash(finding.getEndpointPattern())).append("`\n");
        sb.append("- **Severity**: `").append(valueOrDash(finding.getSeverity())).append("`\n");
        sb.append("- **Confidence**: `").append(formatConfidence(finding.getSizeSimilarity(), finding.getSeverity(), finding.isReplayed())).append("`\n");
        sb.append("- **Owner Actor**: `").append(valueOrDash(finding.getOwnerActorName())).append("`\n");
        sb.append("- **Replay Actor**: `").append(valueOrDash(finding.getReplayerActorName())).append("`\n");
        sb.append("- **Mutation**: `").append(valueOrDash(finding.getMutationType())).append("`\n");
        if (finding.getMutationDescription() != null && !finding.getMutationDescription().isEmpty()) {
            sb.append("- **Mutation Detail**: `").append(finding.getMutationDescription()).append("`\n");
        }
        sb.append("- **Base Status**: `").append(finding.getBaseStatus()).append("`\n");
        sb.append("- **Mutated Status**: `").append(finding.getMutatedStatus()).append("`\n");
        sb.append("- **Base Length**: `").append(finding.getBaseLength()).append("`\n");
        sb.append("- **Mutated Length**: `").append(finding.getMutatedLength()).append("`\n");
        sb.append("- **Similarity**: `").append(String.format("%.1f%%", finding.getSizeSimilarity() * 100)).append("`\n\n");

        sb.append("## How It Became An Issue\n");
        sb.append(buildIssueExplanation(finding)).append("\n\n");

        sb.append("## Requests Used\n");
        appendRequestBlock(sb, "Base Request", finding.getBaseRequest());
        appendRequestBlock(sb, "Mutated Request", finding.getMutatedRequest());
        appendResponseBlock(sb, "Base Response", finding.getBaseResponse());
        appendResponseBlock(sb, "Mutated Response", finding.getMutatedResponse());

        if (finding.getAnalysisNote() != null && !finding.getAnalysisNote().isEmpty()) {
            sb.append("## Analysis Note\n");
            sb.append(finding.getAnalysisNote()).append("\n\n");
        }

        sb.append("## Impact\n");
        if (finding.getLabel() != null && finding.getLabel().contains("DATA_LEAK")) {
            sb.append("A cross-actor data leak was observed. An unauthorized actor could retrieve sensitive content that should have remained isolated.\n\n");
        } else if (finding.getLabel() != null && finding.getLabel().contains("WRITE_BYPASS")) {
            sb.append("The unauthorized actor was able to trigger a state-changing operation. This can lead to data modification, deletion, or privilege escalation.\n\n");
        } else {
            sb.append("The replayed request received access that should have been denied. This indicates an authorization control failure on the endpoint.\n\n");
        }

        sb.append("--- \n");
        sb.append("*Generated by ACAS (Access Control Attack Simulator)*");

        return sb.toString();
    }

    private static void appendRequestBlock(StringBuilder sb, String title, byte[] raw) {
        sb.append("## ").append(title).append("\n");
        sb.append("```http\n");
        sb.append(formatHttpMessage(raw));
        sb.append("\n```\n\n");
    }

    private static void appendResponseBlock(StringBuilder sb, String title, byte[] raw) {
        sb.append("## ").append(title).append("\n");
        sb.append("```http\n");
        sb.append(formatHttpMessage(raw));
        sb.append("\n```\n\n");
    }

    private static String formatHttpMessage(byte[] raw) {
        if (raw == null || raw.length == 0) {
            return "<no data captured>";
        }
        String text = new String(raw, StandardCharsets.ISO_8859_1);
        return text.length() > 2500 ? text.substring(0, 2500) + "\n... (truncated)" : text;
    }

    private static String valueOrDash(String value) {
        return value == null || value.isEmpty() ? "-" : value;
    }

    private static CapturedEndpoint.ProbeResult findBrokenProbe(CapturedEndpoint ep) {
        if (ep == null || ep.getProbes() == null) {
            return null;
        }
        for (CapturedEndpoint.ProbeResult pr : ep.getProbes()) {
            if (pr != null && "BROKEN".equals(pr.verdict)) {
                return pr;
            }
        }
        return null;
    }

    private static String buildIssueExplanation(AcasFinding finding) {
        String label = finding.getLabel() != null ? finding.getLabel() : "";
        String owner = valueOrDash(finding.getOwnerActorName());
        String replay = valueOrDash(finding.getReplayerActorName());

        if (label.contains("ANON_BROKEN")) {
            return "The endpoint responded successfully to an unauthenticated or anonymous replay. The owner request was used as the baseline, and the replayed request showed that the access control check did not require a valid identity.";
        }
        if (label.contains("HORIZ_BROKEN")) {
            return "A same- or lower-privileged actor (" + replay + ") accessed the protected object owned by " + owner + ". The mutated request kept the endpoint shape intact while swapping identity, which indicates horizontal authorization failure.";
        }
        if (label.contains("PRIV_ESC")) {
            return "A lower-privileged actor (" + replay + ") reached functionality reserved for a higher-privileged owner (" + owner + "). The replay request succeeded where the baseline should have remained restricted.";
        }
        if (label.contains("IDOR_DATA_LEAK") || label.contains("DATA_LEAK")) {
            return "The replayed request returned data that belongs to another actor. The response comparison and leaked-field detection show that protected object data crossed the authorization boundary.";
        }
        if (label.contains("WRITE_BYPASS")) {
            return "A state-changing request was accepted for an actor that should not have been allowed to perform the operation. This means the authorization check is inconsistent for write actions.";
        }
        if (label.contains("PARTIAL")) {
            return "The replayed request did not fully match the owner response, but the response shape and status remained close enough to indicate partial authorization bypass or incomplete enforcement.";
        }
        return "The baseline and replayed requests differed in a way that indicates authorization was not enforced consistently for this endpoint.";
    }

    private static String formatConfidence(double similarity, String severity, boolean replayed) {
        if (similarity >= 0.85 && ("CRITICAL".equalsIgnoreCase(severity) || "HIGH".equalsIgnoreCase(severity))) {
            return "Certain";
        }
        if (replayed && similarity >= 0.7) {
            return "Firm";
        }
        return "Tentative";
    }
}
